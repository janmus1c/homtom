#!/usr/bin/env python3
"""Render Roboto (SIL OFL 1.1) into 4-bit alpha glyph tables for gui (the wordmark: gen_wordmark.py).

usage: python3 gen_font.py ROBOTO_VF_TTF > font_data.h      (needs Pillow; host-side only, see gen_assets.sh)
The generated header is a derivative of Roboto: keep the copyright and licence notice below with it.

Styles (docs/UI_DESIGN.md section 6): 12/400, 14/500, 16/500 with ASCII 32..126, Latin-1 and the spec's extras
(č š ž ć đ, − …); 20/400 with ASCII and the spec's extras;
28/400 with digits and the few signs a big number needs. Digits get tabular advances (all as wide as `0`, glyph
centred), so values do not move as they change.

Bitmaps are run-length coded nibbles (decoder: draw_glyph in gui.c): a value 1..14 is one pixel of that alpha; 0 or
15 is followed by a nibble n and stands for n + 1 pixels of that alpha. Two nibbles a byte, high nibble first; every
glyph starts on a byte. Glyphs 32..last are indexed directly; the extras follow in codepoint order and are found by
binary search in the font's `ext` list."""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ASCII = "".join(chr(c) for c in range(32, 127))
LATIN1 = "".join(chr(c) for c in range(0xA1, 0x100) if c != 0xAD)  # Latin-1 letters and signs (no soft hyphen)
SPEC = "°·−…µ²³±čšžČŠŽćĆđĐäöüÄÖÜßé"  # docs/UI_DESIGN.md section 6
EXTRA = "".join(sorted(set(LATIN1 + SPEC)))
BIG = " %+,-.0123456789:CK°−"
SPECS = [  # (c name, px size, weight, charset)
    ("gui_t12", 12, 400, ASCII + EXTRA),
    ("gui_t14", 14, 500, ASCII + EXTRA),
    ("gui_t16", 16, 500, ASCII + EXTRA),
    ("gui_t20", 20, 400, ASCII + SPEC),  # values only (tiles, gauges): the spec's extras, not all of Latin-1
    ("gui_t28", 28, 400, BIG),
]


def pack(px):
    """4-bit alpha pixels -> run-length coded bytes (see the module docstring)"""
    nib, i = [], 0
    while i < len(px):
        v = px[i]
        if v in (0, 15):
            j = i
            while j < len(px) and px[j] == v and j - i < 16:
                j += 1
            nib += [v, j - i - 1]
            i = j
        else:
            nib.append(v)
            i += 1
    if len(nib) & 1:
        nib.append(0)
    return bytes(nib[k] << 4 | nib[k + 1] for k in range(0, len(nib), 2))


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cbytes(name, data):
    out = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("\t" + ",".join(str(x) for x in data[i:i + 24]) + ",")
    out.append("};")
    return out


def font(path, size, weight):
    from PIL import ImageFont
    f = ImageFont.truetype(path, size)
    axes = f.get_variation_axes()
    f.set_variation_by_axes([weight if a["name"] in (b"Weight", "Weight") else 100 for a in axes])
    return f


def glyph_bits(f, ch):
    from PIL import Image, ImageDraw
    l, t, r, b = f.getbbox(ch, anchor="ls")
    w, h = r - l, b - t
    if w <= 0 or h <= 0:
        return 0, 0, 0, 0, b""
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
    px = [(v * 15 + 127) // 255 for v in im.tobytes()]
    return w, h, l, t, pack(px)


def main():
    vf = sys.argv[1]
    out = ["/* Generated by gen_font.py from Roboto, Copyright 2011 The Roboto Project Authors",
           " * (https://github.com/googlefonts/roboto-classic), SIL Open Font License 1.1 (see OFL.txt next to this file).",
           " * Glyph bitmaps are 4-bit alpha, row-major, run-length coded (gen_font.py pack(), gui.c draw_glyph).",
           f" * Source: Roboto[wdth,wght].ttf sha256 {sha(vf)} */"]
    total = 0
    for name, size, weight, charset in SPECS:
        f = font(vf, size, weight)
        asc, desc = f.getmetrics()
        ascii_part = sorted(c for c in charset if ord(c) < 127)
        last = max(ord(c) for c in ascii_part)
        ext = sorted(ord(c) for c in charset if ord(c) >= 127)
        zero = int(round(f.getlength("0")))
        bits = bytearray()
        glyphs = []
        for c in list(range(32, last + 1)) + ext:
            ch = chr(c)
            adv = int(round(f.getlength(ch)))
            if ch not in charset or ch == " ":
                glyphs.append((len(bits), 0, 0, 0, 0, adv))
                continue
            w, h, l, t, data = glyph_bits(f, ch)
            if ch.isdigit():
                l += (zero - adv) // 2
                adv = zero
            glyphs.append((len(bits), w, h, l, asc + t, adv))
            bits += data
        assert len(bits) < 65536
        out += cbytes(f"{name}_bits", bits)
        out.append(f"static const gui_glyph {name}_glyphs[{len(glyphs)}] = {{")
        for g in glyphs:
            out.append("\t{%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f"static const unsigned short {name}_ext[{len(ext)}] = {{ {', '.join(str(c) for c in ext)} }};")
        out.append(f"static const gui_font {name} = {{ {name}_glyphs, {name}_bits, {name}_ext, {len(ext)}, "
                   f"{asc + desc}, {asc}, {last} }};")
        size_b = len(bits) + len(glyphs) * 8 + len(ext) * 2
        total += size_b
        sys.stderr.write(f"{name}: Roboto {size}px/{weight}, {len(glyphs)} glyphs, {len(bits)} bytes bitmap, "
                         f"{size_b} bytes with tables\n")
    sys.stderr.write(f"total {total} bytes\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
