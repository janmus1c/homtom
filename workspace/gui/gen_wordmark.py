#!/usr/bin/env python3
"""Render the brand wordmark into one 4-bit alpha bitmap for the header (gui_wordmark in gui.c).

usage: python3 gen_wordmark.py [PX] > wordmark_data.h        (needs Pillow; host-side only, see gen_assets.sh)

The wordmark is lowercase `homtom` in Poppins SemiBold (brand/fonts, SIL OFL 1.1) with -0.045 em letter spacing
(brand/README.md). It is drawn at 8x the target size with the tracking applied per letter, then box-filtered to 1x, so
the fractional letter positions survive as anti-aliasing (no hinting, as the boot splash). Same run-length coding as
the font tables (gen_font.py pack). The header also gets the ink box and x-height so it can centre the word on the
mark's axis."""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_font import cbytes, pack  # noqa: E402

POPPINS = os.path.join(HERE, "..", "..", "brand", "fonts", "Poppins-SemiBold.ttf")
TEXT, TRACK, K = "homtom", -0.045, 8


def render(size):
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype(POPPINS, size * K)
    W, H, base = size * 6 * K, size * 2 * K, int(size * 1.5) * K
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    x = 0.0
    for ch in TEXT:
        d.text((round(x), base), ch, font=f, fill=255, anchor="ls")
        x += f.getlength(ch) + TRACK * size * K
    small = im.resize((W // K, H // K), Image.BOX)
    bb = small.getbbox()
    xh = f.getbbox("x", anchor="ls")[1] / K   # top of the x-height above the baseline (negative), in px
    return small.crop(bb), bb[0], bb[1] - base // K, xh


def main():
    size = int(sys.argv[1]) if len(sys.argv) > 1 else 16
    crop, dx, dy, xh = render(size)
    w, h = crop.size
    data = pack([(v * 15 + 127) // 255 for v in crop.tobytes()])
    with open(POPPINS, "rb") as fh:
        digest = hashlib.sha256(fh.read()).hexdigest()
    out = ["/* Generated by gen_wordmark.py: the homtom wordmark, Poppins SemiBold %d px, letter spacing %.3f em." % (size, TRACK),
           " * Poppins: Copyright 2020 The Poppins Project Authors (https://github.com/itfoundry/Poppins), SIL Open Font",
           " * License 1.1 (brand/fonts/OFL.txt). 4-bit alpha, run-length coded (gen_font.py pack, gui.c draw_glyph).",
           " * Source: Poppins-SemiBold.ttf sha256 %s */" % digest]
    out += cbytes("gui_wordmark_bits", data)
    out.append("static const gui_glyph gui_wordmark_glyph = { 0, %d, %d, %d, %d, %d };" % (w, h, dx, dy, w + dx))
    out.append("#define GUI_WORDMARK_XH %d\t/* x-height in px (baseline to the top of x) */" % round(-xh))
    out.append("#define GUI_WORDMARK_ADV %d\t/* pen advance: ink width plus its left offset */" % (w + dx))
    print("\n".join(out))
    sys.stderr.write("wordmark %d px: %dx%d ink, offset %d,%d from the pen at the baseline, x-height %.1f, %d bytes\n"
                     % (size, w, h, dx, dy, -xh, len(data)))


if __name__ == "__main__":
    main()
