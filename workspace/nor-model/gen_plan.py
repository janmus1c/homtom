"""Generate tools/devtools/norwrite_plan.h, the compiled-in R1 table for norwrite.c.

Run: python3 gen_plan.py [--check]   (in this directory). --check fails if the header on disk differs.
The table comes from writer_ref.r1_plan on the d48b41 dump and nothing else. Each entry is
(word, stock value, target value); the plan hash is SHA-256 over (u32 LE word, u16 LE target) per entry,
the definition docs/NOR_PLAN.md 9.2 uses (prefix e6135999f3b3e403).
"""

import hashlib
import os
import struct
import sys

import writer_ref as wr

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
STOCK = os.path.join(ROOT, "artifacts", "nor-analysis", "n1-n2-20261107", "nor-n1-linux61.bin")
OUT = os.path.join(ROOT, "tools", "devtools", "norwrite_plan.h")
TARGET_SHA = "87dc81ca967579b424e3e48d1e680685549ee0d73d433d2cfd00c5c4611a384e"
PLAN_SHA_PREFIX = "e6135999f3b3e403"


def c_bytes(hexstr):
    b = bytes.fromhex(hexstr)
    return ", ".join("0x%02x" % x for x in b)


def rows(vals, fmt, per):
    out = []
    for i in range(0, len(vals), per):
        out.append("\t" + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def build():
    with open(STOCK, "rb") as f:
        img = f.read()
    assert wr.sha(img) == wr.STOCK_SHA
    plan, target = wr.r1_plan(img)
    assert wr.sha(target) == TARGET_SHA
    words = [w for w, _ in plan]
    stock = [img[2 * w] | img[2 * w + 1] << 8 for w in words]
    tgt = [v for _, v in plan]
    assert words == sorted(set(words))
    for w, s, t in zip(words, stock, tgt):
        assert t & ~s & 0xFFFF == 0 and t != s
        for k in (0, 1):
            if (s >> 8 * k) & 0xFF != (t >> 8 * k) & 0xFF:
                assert wr.R1_LO <= 2 * w + k <= wr.R1_HI
    plan_sha = hashlib.sha256(b"".join(struct.pack("<IH", w, t) for w, t in plan)).hexdigest()
    assert plan_sha.startswith(PLAN_SHA_PREFIX)
    n = len(plan)
    return f"""/* Generated by workspace/nor-model/gen_plan.py from the d48b41 dump. Do not edit. R1 black-logo plan:
 * {n} words of record 0 (id 0) whose pixel value bytes go to 0x00; every target is a bit-subset of the stock word. */
#define NW_PLAN_N {n}u
#define NW_WORD_LO 0x{words[0]:05x}u
#define NW_WORD_HI 0x{words[-1]:05x}u
#define NW_BYTE_LO 0x{wr.R1_LO:05x}u
#define NW_BYTE_HI 0x{wr.R1_HI:05x}u

static const u32 nw_plan_word[NW_PLAN_N] = {{
{rows(words, "0x%05x", 10)}
}};

static const u16 nw_plan_stock[NW_PLAN_N] = {{
{rows(stock, "0x%04x", 12)}
}};

static const u16 nw_plan_target[NW_PLAN_N] = {{
{rows(tgt, "0x%04x", 12)}
}};

static const u8 nw_sha_stock[32] = {{ {c_bytes(wr.STOCK_SHA)} }};
static const u8 nw_sha_target[32] = {{ {c_bytes(TARGET_SHA)} }};
static const u8 nw_sha_plan[32] = {{ {c_bytes(plan_sha)} }};
"""


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit("norwrite_plan.h differs from the generator output")
        print("norwrite_plan.h matches")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
