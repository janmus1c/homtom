// Bake Poppins glyphs and the tile icons into 4-bit alpha maps for the panel (writes panel/src/assets.c).
// Usage: swift panel/tools/bake-assets.swift brand/fonts panel/src/assets.c
import CoreGraphics
import CoreText
import Foundation

let args = CommandLine.arguments
let fontDir = URL(fileURLWithPath: args[1])
let outPath = args[2]

struct Bitmap {
    var w = 0, h = 0
    var alpha: [UInt8] = []
}

func render(width: Int, height: Int, _ draw: (CGContext) -> Void) -> Bitmap {
    let w = max(width, 1), h = max(height, 1)
    let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1)
    ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
    ctx.setShouldSmoothFonts(false)
    ctx.setAllowsFontSmoothing(false)
    ctx.setShouldAntialias(true)
    draw(ctx)
    let data = ctx.data!.bindMemory(to: UInt8.self, capacity: w * h)
    return Bitmap(w: w, h: h, alpha: Array(UnsafeBufferPointer(start: data, count: w * h)))
}

func pack4(_ b: Bitmap) -> [UInt8] {
    var out: [UInt8] = []
    let rowBytes = (b.w + 1) / 2
    for y in 0..<b.h {
        var row = [UInt8](repeating: 0, count: rowBytes)
        for x in 0..<b.w {
            let v = UInt8((Int(b.alpha[y * b.w + x]) * 15 + 127) / 255)
            row[x / 2] |= x % 2 == 0 ? v << 4 : v
        }
        out += row
    }
    return out
}

var source = """
/* Generated by panel/tools/bake-assets.swift from brand/fonts (Poppins, SIL OFL 1.1). Do not edit. */
#include "assets.h"

"""

func emitBytes(_ name: String, _ bytes: [UInt8]) {
    source += "static const unsigned char \(name)[\(max(bytes.count, 1))] = {\n"
    var line = ""
    for (i, b) in bytes.enumerated() {
        line += String(format: "%d,", b)
        if i % 24 == 23 { source += line + "\n"; line = "" }
    }
    if bytes.isEmpty { line = "0" }
    source += line + "\n};\n"
}

func bakeFont(_ cname: String, file: String, size: CGFloat, tracking: CGFloat) {
    let url = fontDir.appendingPathComponent(file)
    let desc = (CTFontManagerCreateFontDescriptorsFromURL(url as CFURL) as! [CTFontDescriptor])[0]
    let font = CTFontCreateWithFontDescriptor(desc, size, nil)
    let ascent = Int(ceil(CTFontGetAscent(font))), descent = Int(ceil(CTFontGetDescent(font)))
    var bits: [UInt8] = []
    var glyphs: [String] = []
    for code in 32...255 {
        var ch = UniChar(code)
        var g = CGGlyph(0)
        if (code >= 127 && code < 160) || !CTFontGetGlyphsForCharacters(font, &ch, &g, 1) {
            glyphs.append("{0,0,0,0,0,0}")
            continue
        }
        var adv = CGSize.zero
        CTFontGetAdvancesForGlyphs(font, .horizontal, &g, &adv, 1)
        let box = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &g, nil, 1)
        let advance = Int(((adv.width + tracking * size) * 16).rounded())
        if box.width <= 0 || code == 32 || code == 160 {
            glyphs.append("{0,0,0,0,0,\(advance)}")
            continue
        }
        let x0 = Int(floor(box.minX)) - 1, x1 = Int(ceil(box.maxX)) + 1
        let y0 = Int(floor(box.minY)) - 1, y1 = Int(ceil(box.maxY)) + 1
        let bm = render(width: x1 - x0, height: y1 - y0) { ctx in
            ctx.setFillColor(gray: 1, alpha: 1)
            var pos = CGPoint(x: CGFloat(-x0), y: CGFloat(-y0))
            CTFontDrawGlyphs(font, &g, &pos, 1, ctx)
        }
        glyphs.append("{\(bits.count),\(bm.w),\(bm.h),\(x0),\(y1),\(advance)}")
        bits += pack4(bm)
    }
    emitBytes(cname + "_bits", bits)
    source += "static const struct glyph \(cname)_glyphs[224] = {\n" + glyphs.joined(separator: ",\n") + "\n};\n"
    source += "const struct font \(cname) = { \(cname)_glyphs, \(cname)_bits, \(ascent), \(descent) };\n\n"
}

// Icons are drawn on a 24-unit grid, top-left origin, round strokes like the brand mark.
typealias IconDraw = (CGContext) -> Void

func line(_ c: CGContext, _ pts: [(CGFloat, CGFloat)], close: Bool = false) {
    c.move(to: CGPoint(x: pts[0].0, y: pts[0].1))
    for p in pts.dropFirst() { c.addLine(to: CGPoint(x: p.0, y: p.1)) }
    if close { c.closePath() }
    c.strokePath()
}

