func bakeIcon(_ name: String, px: Int, unit: CGFloat, stroke: CGFloat, _ draw: IconDraw) {
    let bm = render(width: px, height: px) { c in
        c.translateBy(x: 0, y: CGFloat(px))
        c.scaleBy(x: CGFloat(px) / unit, y: -CGFloat(px) / unit)
        c.setStrokeColor(gray: 1, alpha: 1)
        c.setFillColor(gray: 1, alpha: 1)
        c.setLineWidth(stroke)
        c.setLineCap(.round)
        c.setLineJoin(.round)
        draw(c)
    }
    emitBytes("icon_\(name)_bits", pack4(bm))
    source += "const struct icon icon_\(name) = { \(bm.w), \(bm.h), icon_\(name)_bits };\n\n"
}

